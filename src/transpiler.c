typedef struct { char *data; size_t size, cap; } Buffer;

static int append(Buffer *b, const char *data, size_t count) {
    if (count > SIZE_MAX - b->size - 1) return 0;
    size_t need = b->size + count + 1;
    if (need > b->cap) {
        size_t cap = b->cap ? b->cap : 256;
        while (cap < need) {
            if (cap > SIZE_MAX / 2) { cap = need; break; }
            cap *= 2;
        }
        char *next = realloc(b->data, cap);
        if (!next) return 0;
        b->data = next;
        b->cap = cap;
    }
    if (count) memcpy(b->data + b->size, data, count);
    b->size += count;
    b->data[b->size] = '\0';
    return 1;
}

static int one(Buffer *b, char c) { return append(b, &c, 1); }
static int id_start(unsigned char c) {
    return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '_' || c >= 0x80;
}
static int id_rest(unsigned char c) {
    return id_start(c) || (c >= '0' && c <= '9');
}
static const char *lookup(const Keyword *list, size_t count,
                          const char *s, size_t n) {
    for (size_t k = 0; k < count; ++k) {
        if (strlen(list[k].from) == n && memcmp(s, list[k].from, n) == 0)
            return list[k].to;
    }
    return NULL;
}

/* Preserve strings, character literals, comments and include paths verbatim. */
char *usagic_transpile(const char *source, size_t size, const char *filename,
                       char *err, size_t err_cap) {
    Buffer out = {0};
    size_t line = 1;
    int bol = 1; /* only horizontal whitespace has appeared on this line */
    int include_tail = 0;
    size_t i = 0;
    if (err_cap) err[0] = '\0';
    if (!source || !filename) goto internal_error;

    /* #line lets GCC/Clang reference the original .usagic line numbers. */
    if (!append(&out, "/* Generated by UsagiC " USAGIC_VERSION " */\n#line 1 \"",
                strlen("/* Generated by UsagiC " USAGIC_VERSION " */\n#line 1 \"")))
        goto memory_error;
    for (const unsigned char *p = (const unsigned char *)filename; *p; ++p) {
        if (*p == '\\' || *p == '"') if (!one(&out, '\\')) goto memory_error;
        if (*p == '\n' || *p == '\r') goto internal_error;
        if (!one(&out, (char)*p)) goto memory_error;
    }
    if (!append(&out, "\"\n", 2)) goto memory_error;

    while (i < size) {
        unsigned char c = (unsigned char)source[i];
        /* At a directive, translate only the directive name after #. */
        if (bol && c == '#') {
            size_t start = i++;
            size_t h = i;
            while (h < size && (source[h] == ' ' || source[h] == '\t')) ++h;
            size_t j = h;
            if (j < size && id_start((unsigned char)source[j])) {
                while (j < size && id_rest((unsigned char)source[j])) ++j;
                const char *replacement = lookup(directives,
                    sizeof directives / sizeof *directives, source + h, j - h);
                if (!append(&out, source + start, h - start)) goto memory_error;
                if (!append(&out, replacement ? replacement : source + h,
                            replacement ? strlen(replacement) : j - h)) goto memory_error;
                include_tail = (replacement && strcmp(replacement, "include") == 0) ||
                               (j - h == 7 && memcmp(source + h, "include", 7) == 0);
                i = j;
                bol = 0;
                continue;
            }
            if (!one(&out, '#')) goto memory_error;
            bol = 0;
            continue;
        }
        if (c == '\n') {
            if (!one(&out, '\n')) goto memory_error;
            ++line; ++i; bol = 1; include_tail = 0;
            continue;
        }
        if (include_tail) {
            if (!one(&out, (char)c)) goto memory_error;
            ++i;
            continue;
        }
        if (c == '"' || c == '\'') {
            const unsigned char quote = c;
            size_t start = i++;
            int closed = 0;
            while (i < size) {
                if (source[i] == '\\' && i + 1 < size) {
                    if (source[i + 1] == '\n') ++line;
                    i += 2;
                } else if ((unsigned char)source[i] == quote) {
                    ++i; closed = 1; break;
                } else if (source[i] == '\n') {
                    /* A raw newline inside a C literal is invalid. */
                    break;
                } else ++i;
            }
            if (!closed) {
                if (err_cap) snprintf(err, err_cap, "%s:%zu: unterminated literal", filename, line);
                goto fail;
            }
            if (!append(&out, source + start, i - start)) goto memory_error;
            bol = 0;
            continue;
        }
        if (c == '/' && i + 1 < size && source[i + 1] == '/') {
            size_t start = i;
            i += 2;
            while (i < size && source[i] != '\n') ++i;
            if (!append(&out, source + start, i - start)) goto memory_error;
            bol = 0;
            continue;
        }
        if (c == '/' && i + 1 < size && source[i + 1] == '*') {
            size_t start = i;
            i += 2;
            int closed = 0;
            int has_newline = 0;
            while (i + 1 < size) {
                if (source[i] == '\n') { ++line; has_newline = 1; }
                if (source[i] == '*' && source[i + 1] == '/') {
                    i += 2; closed = 1; break;
                }
                ++i;
            }
            if (!closed) {
                if (err_cap) snprintf(err, err_cap, "%s:%zu: unterminated comment", filename, line);
                goto fail;
            }
            if (!append(&out, source + start, i - start)) goto memory_error;
            /* A comment is whitespace. A newline resets directive context. */
            if (has_newline) bol = 1;
            continue;
        }
        if (id_start(c)) {
            size_t start = i++;
            while (i < size && id_rest((unsigned char)source[i])) ++i;
            const char *replacement = lookup(keywords,
                sizeof keywords / sizeof *keywords, source + start, i - start);
            if (!append(&out, replacement ? replacement : source + start,
                        replacement ? strlen(replacement) : i - start)) goto memory_error;
            bol = 0;
            continue;
        }
        if (c != ' ' && c != '\t' && c != '\r' && c != '\f' && c != '\v') bol = 0;
        if (!one(&out, (char)c)) goto memory_error;
        ++i;
    }
    return out.data;

memory_error:
    if (err_cap) snprintf(err, err_cap, "out of memory while transpiling");
    goto fail;
internal_error:
    if (err_cap) snprintf(err, err_cap, "invalid transpiler arguments");
fail:
    free(out.data);
    return NULL;
}
